<script setup lang="ts">
import { ref } from 'vue'
import type { AiReview } from '../types/analysis'

defineProps<{
  enabled: boolean | null
  loading: boolean
  error: string | null
  review: AiReview | null
}>()
const emit = defineEmits<{ run: [] }>()

const copied = ref<number | null>(null)

async function copy(text: string, index: number) {
  try {
    await navigator.clipboard.writeText(text)
    copied.value = index
    setTimeout(() => (copied.value = copied.value === index ? null : copied.value), 1500)
  } catch {
    /* clipboard unavailable: user can still select the text */
  }
}
</script>

<template>
  <section class="card" aria-labelledby="ai-heading">
    <div class="mb-1 flex items-center gap-2">
      <h2 id="ai-heading" class="section-title">AI suggestions</h2>
      <span class="rounded-full bg-violet-100 px-2 py-0.5 text-xs font-medium text-violet-800 dark:bg-violet-900/50 dark:text-violet-300">
        optional
      </span>
    </div>

    <p v-if="enabled === false" class="text-sm text-slate-500">
      AI suggestions are turned off. To enable them, add a Groq API key as <code class="code">GROQ_API_KEY</code> in
      <code class="code">backend/.env</code> and restart the backend.
    </p>

    <template v-else-if="!review">
      <p class="mb-4 text-sm text-slate-600 dark:text-slate-400">
        Get a short assessment, draft rewrites of your bullet points, and requirements the skill list doesn't cover.
        This sends your resume text, with email, phone numbers and links removed, and the job description to
        <span class="font-medium">Groq</span>. The match score above doesn't change.
      </p>
      <button type="button" class="btn-primary" :disabled="loading || enabled === null" @click="emit('run')">
        <svg v-if="loading" class="h-4 w-4 animate-spin" viewBox="0 0 24 24" fill="none" aria-hidden="true">
          <circle cx="12" cy="12" r="10" stroke="currentColor" stroke-width="3" class="opacity-25" />
          <path d="M22 12a10 10 0 0 0-10-10" stroke="currentColor" stroke-width="3" stroke-linecap="round" />
        </svg>
        {{ loading ? 'Asking the AI…' : 'Get AI suggestions' }}
      </button>
      <p v-if="error" class="mt-3 text-sm text-rose-600 dark:text-rose-400" role="alert">{{ error }}</p>
    </template>

    <div v-else class="space-y-6">
      <p class="text-sm leading-relaxed text-slate-700 dark:text-slate-300">{{ review.summary }}</p>

      <div v-if="review.rewrites.length">
        <h3 class="mb-1 text-sm font-semibold text-slate-900 dark:text-white">Draft bullet rewrites</h3>
        <p class="mb-3 text-xs text-slate-500">Only use a rewrite if every part of it is true.</p>
        <ul class="space-y-4">
          <li v-for="(r, i) in review.rewrites" :key="i" class="rounded-xl border border-slate-200 p-4 text-sm dark:border-slate-700">
            <p class="text-slate-500 line-through decoration-slate-300 dark:decoration-slate-600">{{ r.original }}</p>
            <div class="mt-2 flex items-start justify-between gap-3">
              <p class="font-medium text-slate-900 dark:text-slate-100">{{ r.suggested }}</p>
              <button type="button" class="btn-ghost shrink-0" @click="copy(r.suggested, i)">
                {{ copied === i ? 'Copied' : 'Copy' }}
              </button>
            </div>
            <p v-if="r.reason" class="mt-2 text-slate-600 dark:text-slate-400">{{ r.reason }}</p>
            <div v-if="r.skills.length" class="mt-2 flex flex-wrap gap-1.5">
              <span v-for="s in r.skills" :key="s" class="rounded bg-slate-100 px-1.5 py-0.5 text-xs text-slate-700 dark:bg-slate-800 dark:text-slate-300">{{ s }}</span>
            </div>
          </li>
        </ul>
      </div>

      <div v-if="review.extra_requirements.length">
        <h3 class="mb-1 text-sm font-semibold text-slate-900 dark:text-white">More requirements in the posting</h3>
        <p class="mb-3 text-xs text-slate-500">
          Found by the AI beyond the standard skill list. Whether your resume mentions each one is checked by text search.
        </p>
        <ul class="divide-y divide-slate-100 dark:divide-slate-800">
          <li v-for="req in review.extra_requirements" :key="req.term" class="flex items-center justify-between gap-3 py-2 text-sm">
            <span class="text-slate-800 dark:text-slate-200">
              {{ req.term }}
              <span v-if="req.priority === 'preferred'" class="ml-1 text-xs text-slate-500">nice to have</span>
            </span>
            <span class="pill" :class="req.found_in_resume ? 'pill-pass' : 'pill-fail'">
              {{ req.found_in_resume ? 'In your resume' : 'Not found' }}
            </span>
          </li>
        </ul>
      </div>

      <p class="text-xs text-slate-400">Generated by {{ review.model }} via Groq. AI output can be wrong; check it before using it.</p>
    </div>
  </section>
</template>
